import mongoose from 'mongoose';

/**
 * Review Schema
 * Single main model representing a customer product review and its AI analysis.
 */
const reviewSchema = new mongoose.Schema(
  {
    // Unique identifier from the CSV (e.g., "R001")
    reviewId: {
      type: String,
      required: [true, 'Review ID is required'],
      unique: true,
      trim: true
    },

    // Name of the product (e.g., "Wireless Noise-Canceling Earbuds")
    product: {
      type: String,
      required: [true, 'Product name is required'],
      trim: true
    },

    // Numeric rating (1-5). Can be null if missing or invalid in CSV
    rating: {
      type: Number,
      default: null,
      min: [1, 'Rating must be at least 1'],
      max: [5, 'Rating cannot exceed 5']
    },

    // Date of the review (preserved as string or date from CSV)
    date: {
      type: String,
      default: () => new Date().toISOString().split('T')[0]
    },

    // Original review text (preserves English, Hindi, Hinglish, emojis, etc.)
    // Note: Empty reviews like R005 are valid edge cases, so default is empty string
    reviewText: {
      type: String,
      default: ''
    },

    // AI-determined sentiment: "positive" | "neutral" | "negative"
    sentiment: {
      type: String,
      enum: {
        values: ['positive', 'neutral', 'negative', null],
        message: '{VALUE} is not a valid sentiment'
      },
      default: null
    },

    // AI-identified topic categories
    topics: {
      type: [String],
      default: []
    },

    // One-sentence summary generated by Gemini in English
    summary: {
      type: String,
      default: ''
    },

    // True if customer has an unresolved issue, complaint, or defective product
    needsReply: {
      type: Boolean,
      default: false
    },

    // Processing status of the review
    analysisStatus: {
      type: String,
      enum: ['pending', 'analyzed', 'analysis_failed', 'insufficient_content'],
      default: 'pending'
    },

    // SHA-256 hash of normalized review text, indexed for fast cache lookups
    reviewHash: {
      type: String,
      required: true,
      index: true
    },

    // Flag for contradictory reviews (e.g., 5-star rating with negative text)
    isRatingMismatch: {
      type: Boolean,
      default: false
    },

    // Professional customer support response (generated on demand in Phase 8)
    suggestedReply: {
      type: String,
      default: ''
    }
  },
  {
    // Automatically manage createdAt and updatedAt timestamps
    timestamps: true
  }
);

// Create and export the Mongoose model
const Review = mongoose.model('Review', reviewSchema);

export default Review;
